#!/usr/bin/env python3
"""Generate a realistic Abaqus/CAE-style sheet-forming input file (and an edited variant for diff demos).

usage: gen_sample.py OUT.inp NX NY NZ [--variant]
NX*NY*NZ C3D8R elements in the blank; NX=1200,NY=1200,NZ=6 gives a ~1.2 GB file.
"""
import sys, io

out, nx, ny, nz = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), int(sys.argv[4])
variant = "--variant" in sys.argv
L, W, T = 200.0, 200.0, 1.2
NL = "\r\n"   # CAE on Windows writes CRLF

def w(f, s):
    f.write(s + NL)

def node_id(i, j, k):
    return 1 + i + j * (nx + 1) + k * (nx + 1) * (ny + 1)

with open(out, "w", newline="", buffering=1 << 22) as f:
    w(f, "*Heading")
    w(f, "** Job name: forming Model name: DP780-cup-draw")
    w(f, "** Generated by: Abaqus/CAE 2025")
    w(f, "*Preprint, echo=NO, model=NO, history=NO, contact=NO")
    w(f, "*Parameter")
    w(f, "punch_speed = 4000.")
    w(f, "blank_t = %g" % T)
    w(f, "**")
    w(f, "** PARTS")
    w(f, "**")
    w(f, "*Part, name=PLATE")
    w(f, "*Node")
    dx, dy, dz = L / nx, W / ny, T / nz
    buf = []
    for k in range(nz + 1):
        z = k * dz
        for j in range(ny + 1):
            y = j * dy
            base = 1 + j * (nx + 1) + k * (nx + 1) * (ny + 1)
            for i in range(nx + 1):
                x = i * dx
                if variant and base + i == 777:
                    x += 0.05
                buf.append("%7d, %12.6g, %12.6g, %12.6g" % (base + i, x, y, z))
            if len(buf) > 200000:
                f.write(NL.join(buf) + NL); buf = []
    if buf:
        f.write(NL.join(buf) + NL); buf = []
    w(f, "*Element, type=C3D8R")
    e = 0
    for k in range(nz):
        for j in range(ny):
            for i in range(nx):
                e += 1
                n1 = node_id(i, j, k); n2 = n1 + 1; n4 = node_id(i, j + 1, k); n3 = n4 + 1
                n5 = node_id(i, j, k + 1); n6 = n5 + 1; n8 = node_id(i, j + 1, k + 1); n7 = n8 + 1
                buf.append("%7d, %7d, %7d, %7d, %7d, %7d, %7d, %7d, %7d" % (e, n1, n2, n3, n4, n5, n6, n7, n8))
                if len(buf) > 200000:
                    f.write(NL.join(buf) + NL); buf = []
    if buf:
        f.write(NL.join(buf) + NL); buf = []
    nn = (nx + 1) * (ny + 1) * (nz + 1)
    w(f, "*Nset, nset=PLATE-ALL, generate")
    w(f, "      1, %7d,       1" % nn)
    w(f, "*Elset, elset=PLATE-ALL, generate")
    w(f, "      1, %7d,       1" % e)
    for name, ids in (("SYM-X", [node_id(0, j, k) for k in range(nz + 1) for j in range(ny + 1)]),
                      ("SYM-Y", [node_id(i, 0, k) for k in range(nz + 1) for i in range(nx + 1)])):
        w(f, "*Nset, nset=%s" % name)
        for a in range(0, len(ids), 16):
            w(f, ", ".join("%d" % v for v in ids[a:a + 16]) + ("," if a + 16 >= len(ids) else ""))
    top0 = (nz - 1) * nx * ny + 1
    w(f, "*Elset, elset=_TOP_S2, internal, generate")
    w(f, " %7d, %7d,       1" % (top0, e))
    w(f, "*Surface, type=ELEMENT, name=TOP")
    w(f, "_TOP_S2, S2")
    w(f, "** Section: PLATE-SEC")
    if variant:
        w(f, "*Solid Section, elset=PLATE-ALL, material=STEEL-DP780")
    else:
        w(f, "*Solid Section, elset=PLATE-ALL, materal=STEEL-DP780")
    w(f, ",")
    w(f, "*End Part")
    # rigid tools
    for pname, n, size, z0 in (("PUNCH", 120, 120.0, 0.0), ("DIE", 160, 260.0, 0.0)):
        w(f, "**")
        w(f, "*Part, name=%s" % pname)
        w(f, "*Node")
        h = size / n
        for j in range(n + 1):
            for i in range(n + 1):
                buf.append("%7d, %12.6g, %12.6g, %12.6g" % (1 + i + j * (n + 1), -size / 2 + i * h, -size / 2 + j * h, z0))
        f.write(NL.join(buf) + NL); buf = []
        w(f, "*Element, type=R3D4")
        e2 = 0
        for j in range(n):
            for i in range(n):
                e2 += 1
                a = 1 + i + j * (n + 1)
                buf.append("%7d, %7d, %7d, %7d, %7d" % (e2, a, a + 1, a + n + 2, a + n + 1))
        f.write(NL.join(buf) + NL); buf = []
        w(f, "*Nset, nset=%s-ALL, generate" % pname)
        w(f, "      1, %7d,       1" % ((n + 1) ** 2))
        w(f, "*Elset, elset=%s-ALL, generate" % pname)
        w(f, "      1, %7d,       1" % e2)
        w(f, "*Surface, type=ELEMENT, name=%s-SURF" % pname)
        w(f, "%s-ALL, SPOS" % pname)
        w(f, "*End Part")
    w(f, "**")
    w(f, "** ASSEMBLY")
    w(f, "**")
    w(f, "*Assembly, name=Assembly")
    w(f, "**")
    w(f, "*Instance, name=PLATE-1, part=PLATE")
    w(f, "*End Instance")
    w(f, "**")
    w(f, "*Instance, name=PUNCH-1, part=PUNCH")
    w(f, "          100.,          100.,           1.3")
    w(f, "*End Instance")
    w(f, "**")
    w(f, "*Instance, name=DIE-1, part=DIE")
    w(f, "          100.,          100.,           -0.1")
    w(f, "*End Instance")
    w(f, "**")
    w(f, "*Node")
    w(f, "      1,         100.,         100.,          3O." if not variant else "      1,         100.,         100.,          30.")
    w(f, "      2,         100.,         100.,          -10.")
    w(f, "*Nset, nset=RP-PUNCH")
    w(f, " 1,")
    w(f, "*Nset, nset=RP-DIE")
    w(f, " 2,")
    w(f, "*Nset, nset=SYM-X, instance=PLATE-1")
    w(f, " SYM-X,")
    w(f, "*Nset, nset=SYM-Y, instance=PLATE-1")
    w(f, " SYM-Y,")
    w(f, "*Rigid Body, ref node=RP-PUNCH, elset=PUNCH-1.PUNCH-ALL")
    w(f, "*Rigid Body, ref node=RP-DIE, elset=DIE-1.DIE-ALL")
    w(f, "*End Assembly")
    w(f, "*Amplitude, name=PUNCH-STROKE, definition=SMOOTH STEP")
    w(f, "             0.,              0.,           0.005,              1.")
    w(f, "**")
    w(f, "** MATERIALS")
    w(f, "**")
    w(f, "*Material, name=STEEL-DP780")
    w(f, "*Density")
    w(f, "7.85e-09,")
    w(f, "*Elastic")
    w(f, "205000., 0.3" if variant else "210000., 0.3")
    w(f, "*Plastic")
    sy = 480.0
    for i in range(18):
        ep = 0.02 * i
        w(f, "%8.2f, %6.3f" % (sy * (1 + ep / 0.004) ** 0.12 if i else sy, ep))
    w(f, "*Material, name=TOOL-STEEL")
    w(f, "*Density")
    w(f, "7.85e-09,")
    w(f, "*Elastic" if variant else "*Elastik")
    w(f, "210000., 0.3")
    w(f, "**")
    w(f, "** INTERACTION PROPERTIES")
    w(f, "**")
    w(f, "*Surface Interaction, name=FRIC")
    w(f, "1.,")
    w(f, "*Friction")
    w(f, "0.10," if variant else "0.12,")
    w(f, "*Surface Behavior, pressure-overclosure=HARD")
    w(f, "**")
    w(f, "** BOUNDARY CONDITIONS")
    w(f, "**")
    w(f, "** Name: SYM-X Type: Symmetry/Antisymmetry/Encastre")
    w(f, "*Boundary")
    w(f, "SYM-X, XSYMM")
    w(f, "** Name: SYM-Y Type: Symmetry/Antisymmetry/Encastre")
    w(f, "*Boundary")
    w(f, "SYM-Y, YSYMM")
    w(f, "** Name: DIE-FIX Type: Symmetry/Antisymmetry/Encastre")
    w(f, "*Boundary")
    w(f, "RP-DIE, ENCASTRE" if variant else "FIX-DIE, ENCASTRE")
    w(f, "** ----------------------------------------------------------------")
    w(f, "**")
    w(f, "** STEP: Forming")
    w(f, "**")
    w(f, "*Step, name=Forming, nlgeom=YES")
    w(f, "*Dynamic, Explicit")
    w(f, ", 0.005")
    if not variant:
        w(f, "*Bulk Viscosity")
        w(f, "0.06, 1.2")
    w(f, "** Mass Scaling: Semi-Automatic")
    w(f, "**               Whole Model")
    w(f, "*Fixed Mass Scaling, factor=100.")
    w(f, "**")
    w(f, "** BOUNDARY CONDITIONS")
    w(f, "**")
    w(f, "** Name: PUNCH-MOVE Type: Velocity/Angular velocity")
    w(f, "*Boundary, type=VELOCITY, amplitude=PUNCH-STROKE")
    w(f, "RP-PUNCH, 1, 1")
    w(f, "RP-PUNCH, 2, 2")
    w(f, "RP-PUNCH, 3, 3, -<punch_speed>" if variant else "RP-PUNCH, 3, 3, -<punch_sped>")
    w(f, "**")
    w(f, "** INTERACTIONS")
    w(f, "**")
    w(f, "** Interaction: GENERAL")
    w(f, "*Contact, op=NEW")
    w(f, "*Contact Inclusions, ALL EXTERIOR")
    w(f, "*Contact Property Assignment")
    w(f, " ,  , FRIC")
    w(f, "**")
    w(f, "** OUTPUT REQUESTS")
    w(f, "**")
    w(f, "*Restart, write, number interval=1, time marks=NO")
    w(f, "**")
    w(f, "** FIELD OUTPUT: F-Output-1")
    w(f, "**")
    w(f, "*Output, field, number interval=40")
    w(f, "*Node Output")
    w(f, "A, RF, U, V" if variant else "RF, U, V")
    w(f, "*Element Output, directions=YES")
    w(f, "LE, PE, PEEQ, S, STH")
    w(f, "**")
    w(f, "** HISTORY OUTPUT: H-Output-1")
    w(f, "**")
    w(f, "*Output, history, variable=PRESELECT")
    w(f, "*End Step")
print("done", out)
